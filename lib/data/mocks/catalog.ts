function productImage(src: string, alt: string): ProductImage {
  return { src, alt };
}

/** Demo catalog photos via Unsplash CDN (not Pinterest hotlinks). */
function unsplash(photoPath: string, alt: string): ProductImage {
  return productImage(
    `https://images.unsplash.com/${photoPath}?auto=format&fit=crop&w=900&h=675&q=80`,
    alt,
  );
}

